/** "Oct – Mar": the best months as a range, or a short list when they wrap or skip. */
export function monthsLabel(months: number[]) {
  if (months.length >= 12) return "All year";
  const short = (m: number) => MONTH_NAMES[m - 1].slice(0, 3);
  // Runs of consecutive months, wrapping December into January.
  const runs: number[][] = [];
  for (const m of months) {
    const last = runs[runs.length - 1];
    if (last && (last[last.length - 1] % 12) + 1 === m) last.push(m);
    else runs.push([m]);
  }
  return runs.map((r) => (r.length === 1 ? short(r[0]) : `${short(r[0])} – ${short(r[r.length - 1])}`)).join(", ");
}

export const inr = (n: number) => `₹${Math.round(n).toLocaleString("en-IN")}`;

/** The trip for two at a budget level: per-person day cost × days × 2. */
export const tripTotal = (t: TripIdea, level: 0 | 1 | 2) => t.budget[level] * t.days * 2;

/** Trips in season this month (the order they're written in). */
export const inSeason = (month = new Date().getMonth() + 1) => TRIP_IDEAS.filter((t) => t.months.includes(month));

/** Other trips like this one: same tags or region first. */
export function relatedTrips(t: TripIdea, n = 6) {
  return TRIP_IDEAS.filter((o) => o.slug !== t.slug)
    .map((o) => ({ o, score: o.tags.filter((x) => t.tags.includes(x)).length * 2 + (o.region === t.region ? 3 : 0) + (o.country === t.country ? 1 : 0) }))
    .sort((a, b) => b.score - a.score)
    .slice(0, n)
    .map((x) => x.o);
}

/** Questions people search, answered from the trip's own data. */
export function tripFaqs(t: TripIdea) {
  const [lo, mid, hi] = t.budget;
  const faqs = [
    { q: `How many days are enough for ${t.name}?`, a: `${t.days} ${t.days === 1 ? "day is" : "days are"} enough to see the highlights: ${t.highlights.slice(0, 3).map((h) => h[0]).join(", ")}. Add a day or two if you like a slower pace.` },
    { q: `How much does a ${t.days}-day ${t.name} trip cost?`, a: `Roughly ${inr(lo)} a day per person on a budget, ${inr(mid)} mid-range and ${inr(hi)}+ for luxury, not counting travel to get there. For two people mid-range, that's about ${inr(tripTotal(t, 1))} for ${t.days} days.` },
    { q: `What is the best time to visit ${t.name}?`, a: `${monthsLabel(t.months)}. ${t.why}` },
    { q: `Where should I stay in ${t.name}?`, a: t.stays.map((x) => `${x.tier}: ${x.name} (${x.area}), from about ${inr(x.from)} a night.`).join(" ") },
    { q: `How do I reach ${t.name}?`, a: t.reach },
  ];
  if (t.visa) faqs.push({ q: `Do Indians need a visa or permit for ${t.name}?`, a: t.visa });
  return faqs;
}
