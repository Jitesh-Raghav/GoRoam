// Writes src/components/site/icon-paths.ts (and the adventure kinds' own set): the SVG
// paths of only the icons, and only the weights, that icons.tsx (and adventure-kind.tsx)
// ask for. Phosphor's components carry all six weights each, which put ~150 KB (gzipped)
// of unused paths on every page.
//
//   node scripts/build-icons.mjs        (run after adding a make("Name", "weight", …) line)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const defs = path.join(root, "node_modules/@phosphor-icons/react/dist/defs");
/** A defs file is `import * as a from "react"; const e = new Map([...]); export { e as default };`. */
function weightsOf(icon) {
  const text = readFileSync(path.join(defs, `${icon}.es.js`), "utf8");
  const reactName = text.match(/import \* as (\w+) from "react";/)?.[1];
  const out = text.match(/export \{\s*(\w+) as default\s*\};/)?.[1];
  if (!reactName || !out) throw new Error(`Unexpected format in ${icon}.es.js`);
  const body = text.replace(/import \* as \w+ from "react";/, "").replace(/export \{[^}]*\};/, "");
  return new Function(reactName, `${body}\nreturn ${out};`)(React);
}

// Each source file's icons go to a paths file of their own: the shared set every page loads,
// and the adventure kinds' icons, which only the server-rendered adventure cards draw.
const TARGETS = [
  { source: "src/components/site/icons.tsx", out: "src/components/site/icon-paths.ts", name: "ICON_PATHS" },
  { source: "src/components/seo/adventure-kind.tsx", out: "src/components/seo/kind-icon-paths.ts", name: "KIND_ICON_PATHS" },
];

for (const { source, out, name } of TARGETS) {
  const text = readFileSync(path.join(root, source), "utf8");
  // make("MapPin", "duotone", "MapPin") → MapPin in duotone.
  const wanted = new Map();
  for (const [, icon, weight] of text.matchAll(/make\("([A-Za-z]+)",\s*"([a-z]+)"/g)) {
    if (!wanted.has(icon)) wanted.set(icon, new Set());
    wanted.get(icon).add(weight);
  }
  const entries = [];
  for (const [icon, weights] of [...wanted].sort(([a], [b]) => a.localeCompare(b))) {
    const map = weightsOf(icon);
    for (const weight of [...weights].sort()) {
      const el = map.get(weight);
      if (!el) throw new Error(`${icon} has no "${weight}" weight`);
      entries.push(`  "${icon}:${weight}": ${JSON.stringify(renderToStaticMarkup(el))},`);
    }
  }
  writeFileSync(
    path.join(root, out),
    `// Generated by scripts/build-icons.mjs from @phosphor-icons/react. Do not edit by hand:\n// add a make("Name", "weight", …) line to ${path.basename(source)} and run \`npm run icons\`.\nexport const ${name}: Record<string, string> = {\n${entries.join("\n")}\n};\n`
  );
  console.log(`${path.basename(out)}: ${entries.length} icon weights from ${wanted.size} icons`);
}
